"""This module is the first component of the architecture of a generator of Portuguese diminutives. It extracts possible diminutive formation bases from existing nouns and adjectives encoded in MorphoBr's format, as described in the following paper:

ALENCAR, Leonel Figueiredo de;  CUCONATO , Bruno; RADEMAKER, Alexandre. MorphoBr: an open source large-coverage full-form lexicon for morphological analysis of Portuguese. Texto Livre: Linguagem e Tecnologia, Belo Horizonte, v. 11, n. 3, p. 1-25, set.- dez. 2018. 
ISSN 1983-3652 
DOI: 10.17851/1983-3652.11.3.1-25
http://www.periodicos.letras.ufmg.br/index.php/textolivre/article/view/14294. 


Unplausible bases are filtered out, see details below. The extracted bases are converted to spaced-text format and written to different files, according to the classification expected by the finite-state grammar in the morphotactic-grammar.lexc file. Some examples may help clarify the pipeline:

Input in MorphoBr' format:

agulhão	agulha+N+AUG+M+SG
agulhões	agulha+N+AUG+M+PL
agulhona	agulha+N+AUG+F+SG
agulhonas	agulha+N+AUG+F+PL


Output generated by this module (written to different files):

a g u l h a +N +AUG
a g u l h ã o

a g u l h a +N +AUG
a g u l h õ e s

a g u l h a +N +AUG
a g u l h o n a

a g u l h a +N +AUG
a g u l h o n a s


"""
import os, re

EXCLUDE_TAGS = ["+DIM", "+SUPER"]
EXTENSION = ".stxt"

"""Regex pattern matching itens that can not function as bases for
morphological derivations. This includes one or more consonants before a space
at the beginning of a line, for example:
b       b+N+M+SG
c       c+N+M+SG
d       d+N+M+SG

These itens are in fact abbreviations. As such, they cannot feed diminutive formation,
e.g. *bzinho 'little b' is ungrammatical (the correct form is 'bezinho', from 'bê', the name of
letter b).
The regex pattern also matches abbreviations such as 'ha' (for hectare) and chemical symbols ('Ba', 'Ca', etc.).
"""
CONS = "[bcdfghjklmnpqrstvwxyz]"
ABB = re.compile(r"(?i)(%s{1,}|%s[aeo])\s" % (CONS, CONS))

# Base files expected by morphotactic-grammar.lexc, by kind, gender and number.
KINDS = {"aug": "aug_%s_%s", "wdlm": "wdlm_in_s_%s_%s", "other": "other_%s_%s"}
NONCANON = {("M", "SG"): "masc_in_a_sg", ("M", "PL"): "masc_in_a_pl",
            ("F", "SG"): "fem_in_o_sg", ("F", "PL"): "fem_in_o_pl"}


def ignore_entry(entry):
    """True if the entry can be a base (the name is kept from the original)."""
    if entry == "" or any(tag in entry for tag in EXCLUDE_TAGS) or ABB.match(entry):
        return False
    return True


def space(word):
    return " ".join(list(word))


def convert_entry(word, lemma, tags):
    return "%s %s\n%s" % (space(lemma), "+%s" % " +".join(tags), space(word))


def parse_entry(entry):
    word, parse = re.split(r"\s+", entry)
    lemma, tags = re.split(r"\+", parse, maxsplit=1)
    return word, lemma, tags


def WordLemmaInS(word, lemma):
    return word.endswith("s") and lemma.endswith("s") and word == lemma


def NonCanonGendMarker(word, tags):
    return bool("-" in word and "+M+PL" in tags and word.endswith("a")
                or "-" in word and "+F+PL" in tags and word.endswith("o")
                or "+M+SG" in tags and word.endswith("a")
                or "+M+PL" in tags and word.endswith("as")  # N-N compounds like 'aços-liga'
                or "+F+SG" in tags and word.endswith("o")
                or "+F+PL" in tags and word.endswith("os"))  # N-N compounds like 'amostras-tipo'


def gend_num(tags):
    """Genders and numbers of an analysis. Uniform words (without gender) and
    invariable words (without number) count for both, following the MorphoBr
    conventions adopted in 2021 (e.g. inteligente+A+SG, lápis+N+M)."""
    t = re.split(r"\+", tags)
    gens = [g for g in ("M", "F") if g in t] or ["M", "F"]
    nums = [n for n in ("SG", "PL") if n in t] or ["SG", "PL"]
    return [(g, n) for g in gens for n in nums]


def classify(word, lemma, tags):
    """Yields (base file name, spaced-text entry) for each gender and number of
    the entry. The gender and number are expanded before the classification, so
    that e.g. a uniform masculine in -a (o artista) is a non-canonical gender
    marker (o artistinha), like entries with explicit gender."""
    for g, n in gend_num(tags):
        t = "+%s+%s" % (g, n)
        if "+AUG" in tags:
            yield KINDS["aug"] % (g.lower(), n.lower()), convert_entry(word, lemma, re.split(r"\+", tags)[:2])
        elif WordLemmaInS(word, lemma):
            yield KINDS["wdlm"] % (g.lower(), n.lower()), convert_entry(word, lemma, tags[0])
        elif NonCanonGendMarker(word, t):
            yield NONCANON[(g, n)], convert_entry(word, lemma, tags[0])
        else:
            yield KINDS["other"] % (g.lower(), n.lower()), convert_entry(word, lemma, tags[0])


def extract(lines, outdir, allowed=None):
    """Writes the base files for the given dictionary lines (form<TAB>analysis)
    to outdir. If allowed is given, only entries whose (lemma, category) is in
    it are used as bases."""
    names = [k % (g, n) for k in KINDS.values() for g in "mf" for n in ("sg", "pl")] + list(NONCANON.values())
    files = {name: open(os.path.join(outdir, name + EXTENSION), "w", encoding="utf-8") for name in names}
    try:
        for line in lines:
            entry = line.strip()
            if not ignore_entry(entry):
                continue
            word, lemma, tags = parse_entry(entry)
            if allowed is not None and (lemma, tags.split("+")[0]) not in allowed:
                continue
            for name, stxt in classify(word, lemma, tags):
                files[name].write("%s\n\n" % stxt)
    finally:
        for fh in files.values():
            fh.close()
